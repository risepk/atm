    /**
     * Render the core document body
     */
    protected function renderDocumentBody(array $statementData): string {
        $account = $statementData['account'] ?? [];
        $transactions = $statementData['transactions'] ?? [];

        $opening = CurrencyHelper::format($statementData['opening_balance'] ?? '0.00');
        $closing = CurrencyHelper::format($statementData['closing_balance'] ?? '0.00');
        $totalDebit = CurrencyHelper::format($statementData['total_debit'] ?? '0.00');
        $totalCredit = CurrencyHelper::format($statementData['total_credit'] ?? '0.00');

        $startDateFormatted = $this->formatPeriodDate($statementData['start_date'] ?? date('Y-01-01'));
        $endDateFormatted = $this->formatPeriodDate($statementData['end_date'] ?? date('Y-m-d'));
        
        $printDate = !empty($account['print_date']) ? $account['print_date'] : date('d M Y H:i:s');
        $printDateFormatted = strtoupper(date('d M Y H:i:s', strtotime($printDate) ?: time()));

        // Customer & Account Details
        $accountTitle = htmlspecialchars(strtoupper($account['account_title'] ?? $account['account_identifier'] ?? ''), ENT_QUOTES, 'UTF-8');
        $accountNo = htmlspecialchars($account['account_number'] ?? $account['account_identifier'] ?? '', ENT_QUOTES, 'UTF-8');
        $iban = htmlspecialchars($account['iban'] ?? '', ENT_QUOTES, 'UTF-8');
        $oldAccountNo = htmlspecialchars($account['old_account_no'] ?? '', ENT_QUOTES, 'UTF-8');

        // Customer Address Lines
        $addressLines = [];
        if (!empty($account['address'])) {
            $rawLines = preg_split('/\r\n|\r|\n/', trim((string)$account['address']));
            foreach ($rawLines as $l) {
                $trimmed = trim($l);
                if ($trimmed !== '') {
                    $addressLines[] = htmlspecialchars(strtoupper($trimmed), ENT_QUOTES, 'UTF-8');
                }
            }
        }
        if (empty($addressLines)) {
            $addressLines = [
                'PLOT 12-C, COMMERCIAL AREA',
                'ISLAMABAD-PK'
            ];
        }

        // Branch Details
        $branchCodeAndName = !empty($account['branch_name']) ? htmlspecialchars(strtoupper(trim((string)$account['branch_name'])), ENT_QUOTES, 'UTF-8') : '0317-JINNAH SUPER BR-ISD';
        $branchAddress = !empty($account['branch_address']) ? htmlspecialchars(strtoupper(trim((string)$account['branch_address'])), ENT_QUOTES, 'UTF-8') : 'PLOT NO Q-13 COLLAGE ROAD F-7 ISLAMABAD';
        
        $product = !empty($account['product']) ? htmlspecialchars(trim((string)$account['product']), ENT_QUOTES, 'UTF-8') : (!empty($account['account_type']) ? htmlspecialchars(trim((string)$account['account_type']), ENT_QUOTES, 'UTF-8') : 'Meezan Rupee Current A/c');
        $currency = !empty($account['currency']) ? htmlspecialchars(trim((string)$account['currency']), ENT_QUOTES, 'UTF-8') : 'Pakistan Rupee';
        if (strtoupper($currency) === 'PKR') {
            $currency = 'Pakistan Rupee';
        }
        
        $generatedBy = !empty($account['generated_by']) ? htmlspecialchars(trim((string)$account['generated_by']), ENT_QUOTES, 'UTF-8') : 'MOIN.31188';

        // Count credit and debit transactions
        $creditCount = 0;
        $debitCount = 0;
        foreach ($transactions as $t) {
            if (CurrencyHelper::comp($t['credit'] ?? '0.00', '0.00') > 0) {
                $creditCount++;
            }
            if (CurrencyHelper::comp($t['debit'] ?? '0.00', '0.00') > 0) {
                $debitCount++;
            }
        }

        // Precompute which transaction row is the LAST transaction of each date
        // In authentic Meezan statements, the Balance is printed on the last row of each date!
        $lastRowOfDate = [];
        $totalTxCount = count($transactions);
        for ($i = 0; $i < $totalTxCount; $i++) {
            // Compare calendar dates, not the raw DB value. This is important when
            // the transaction date contains a time component (YYYY-MM-DD HH:MM:SS).
            $currentRawDate = (string)($transactions[$i]['date'] ?? '');
            $currentTs = strtotime($currentRawDate);
            $currentDate = $currentTs ? date('Y-m-d', $currentTs) : trim($currentRawDate);

            if ($i + 1 < $totalTxCount) {
                $nextRawDate = (string)($transactions[$i + 1]['date'] ?? '');
                $nextTs = strtotime($nextRawDate);
                $nextDate = $nextTs ? date('Y-m-d', $nextTs) : trim($nextRawDate);
            } else {
                $nextDate = null;
            }

            if ($nextDate === null || $nextDate !== $currentDate) {
                $lastRowOfDate[$i] = true;
            }
        }

