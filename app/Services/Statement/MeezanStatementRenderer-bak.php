                <?php if (!empty($account['bank_logo'])): ?>
                    <img src="/atm/public/<?= htmlspecialchars($account['bank_logo'], ENT_QUOTES, 'UTF-8') ?>" alt="Meezan Bank" style="display:none;">
                <?php endif; ?>
                <div class="mezn-branch-info"><?= $branchCodeAndName ?></div>
                <div class="mezn-branch-info"><?= $branchAddress ?></div>
                <div class="mezn-doc-title">QUICK ACCOUNT TRANSACTIONS</div>
            </div>

            <!-- Customer & Account Info Table -->
            <table class="mezn-account-meta-table">
                <tr>
                    <!-- Left: Customer Information -->
                    <td style="width: 30%;">
                        <div class="mezn-cust-title"><?= $accountTitle ?></div>
                        <div class="mezn-cust-address">
                            <?php foreach ($addressLines as $addrLine): ?>
                                <div><?= $addrLine ?></div>
                            <?php endforeach; ?>
                        </div>
                    </td>
                    <!-- Right: Account Metadata -->
                    <td style="width: 70%; padding-left: 4px;">
                        <div class="mezn-meta-row"><span class="mezn-meta-lbl">IBAN :</span><span class="mezn-meta-val"><?= $iban ?></span></div>
                        <div class="mezn-meta-row"><span class="mezn-meta-lbl">Old Account No :</span><span class="mezn-meta-val"><?= $oldAccountNo ?></span></div>
                        <div class="mezn-meta-row"><span class="mezn-meta-lbl">Account No :</span><span class="mezn-meta-val"><?= $accountNo ?></span></div>
                        <div class="mezn-meta-row"><span class="mezn-meta-lbl">Product :</span><span class="mezn-meta-val"><?= $product ?></span></div>
                        <div class="mezn-meta-row"><span class="mezn-meta-lbl">Currency :</span><span class="mezn-meta-val"><?= $currency ?></span></div>
                        <div class="mezn-meta-row"><span class="mezn-meta-lbl">From Date :</span><span class="mezn-meta-val"><?= $startDateFormatted ?></span></div>
                        <div class="mezn-meta-row"><span class="mezn-meta-lbl">To Date :</span><span class="mezn-meta-val"><?= $endDateFormatted ?></span></div>
                        <div class="mezn-meta-row mezn-meta-generated"><span class="mezn-meta-lbl">Generated By:</span><span class="mezn-print-value"><?= $generatedBy ?></span></div>
                    </td>
                </tr>
            </table>

            <!-- Opening Balance Banner -->
            <div class="mezn-banner-row mezn-closing-row">
                <span class="mezn-banner-label">&lt;= &nbsp;O P E N I N G &nbsp;- &nbsp;B A L A N C E &nbsp;=&gt;</span>
                <span class="mezn-banner-amount"><?= $opening ?></span>
            </div>

            <!-- Transaction Table -->
            <table class="mezn-table">
                <thead>
                    <tr>
                        <th class="col-m-date">Date(DD/MM)</th>
                        <th class="col-m-val">Value</th>
                        <th class="col-m-doc">*******Doc.No*******</th>
                        <th class="col-m-part">***Particulars******</th>
                        <th class="col-m-debit">*******Debit********</th>
