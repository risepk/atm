                            $creditVal = (string)($tx['credit'] ?? '0.00');
                            
                            $hasDebit = CurrencyHelper::comp($debitVal, '0.00') > 0;
                            $hasCredit = CurrencyHelper::comp($creditVal, '0.00') > 0;
                            
