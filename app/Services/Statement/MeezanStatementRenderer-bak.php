                        <th class="col-m-bal">******Balance*******</th>
                        <th class="col-m-link"></th>
                    </tr>
                </thead>
                <tbody>
                    <?php if (empty($transactions)): ?>
                        <tr>
                            <td colspan="8" style="padding: 16px; text-align: center; color: #555; font-style: italic;">No transactions recorded for this period.</td>
