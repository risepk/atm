    protected string $formatName = 'Meezan Bank Statement Layout';

    public function getSupportedFormatCode(): string {
        return $this->formatCode;
    }

    public function getFormatName(): string {
        return $this->formatName;
    }

    /**
     * Format date as DD/MM/YY (e.g. 02/07/25) matching Meezan table columns
     */
    protected function formatDateDmy(?string $dateStr): string {
        if (!$dateStr) return '';
        $ts = strtotime($dateStr);
        return $ts ? date('d/m/y', $ts) : $dateStr;
    }

    /**
     * Format date as DD MMM YYYY in uppercase (e.g. 01 JUL 2025) for header periods
     */
    protected function formatPeriodDate(?string $dateStr): string {
        if (!$dateStr) return '';
        $ts = strtotime($dateStr);
        return $ts ? strtoupper(date('d M Y', $ts)) : $dateStr;
    }

