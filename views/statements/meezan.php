<script>
var accountsList = <?= json_encode(array_values($accounts), JSON_HEX_TAG | JSON_HEX_APOS | JSON_HEX_QUOT | JSON_HEX_AMP) ?>;
var accountsByIdentifier = {};
var accountsById = {};

accountsList.forEach(function(a) {
    var ident = String(a.account_identifier || a.id).trim().toLowerCase();
    accountsByIdentifier[ident] = a;
    accountsById[a.id] = a;
});

function resolveMeezanAccount() {
    var q = $.trim($('#meezan-account-code-input').val()).toLowerCase();
    if (!q) return null;
    if (accountsByIdentifier[q]) return accountsByIdentifier[q];
    var match = accountsList.find(function(a) {
        return String(a.account_title).toLowerCase() === q || String(a.account_number).toLowerCase() === q;
    });
    return match || null;
}

function populateMeezanFields(acc) {
    if (!acc) return;
    $('#meezan-account-id').val(acc.id);
    $('#meezan-customer-title').val(acc.account_title || '');
    $('#meezan-account-number').val(acc.account_number || '');
    $('#meezan-customer-address').val(acc.address || '');
    $('#meezan-opening-balance').val(parseFloat(acc.initial_balance || 0).toLocaleString('en-US', { minimumFractionDigits: 2, maximumFractionDigits: 2 }));
    $('#meezan-iban').val(acc.iban || '');
    $('#meezan-branch-name').val(acc.branch_name || '');
}

$('#meezan-account-code-input').on('input change', function() {
    var acc = resolveMeezanAccount();
    if (acc) {
        populateMeezanFields(acc);
    }
});

$('#meezan-statement-form').on('submit', function(e) {
    e.preventDefault();
    executeMeezanGeneration();
});

function executeMeezanGeneration() {
    var acc = resolveMeezanAccount();
    var accId = acc ? acc.id : $('#meezan-account-id').val();

    if (!accId) {
        alert('Please enter or select a valid Account Code / Number.');
        $('#meezan-account-code-input').focus();
        return;
    }

    var payload = {
        account_id: accId,
        start_date: $('#meezan-start-date').val(),
        end_date: $('#meezan-end-date').val(),
        format: 'meezan',
        bank_name: 'Meezan Bank Limited',
        account_title: $('#meezan-customer-title').val(),
        account_number: $('#meezan-account-number').val(),
        address: $('#meezan-customer-address').val(),
        branch_name: $('#meezan-branch-name').val() || '',
        branch_address: $('#meezan-branch-address').val() || '',
        old_account_no: $('#meezan-old-account-no').val() || '',
        product: $('#meezan-product').val() || '',
        currency: $('#meezan-currency').val() || 'Pakistan Rupee',
        iban: $('#meezan-iban').val() || '',
        opening_balance: $('#meezan-opening-balance').val(),
        generated_by: $('#meezan-generated-by').val() || '',
        print_date: $('#meezan-print-date').val() || ''
    };

    $('#meezan-output-placeholder').html('<div class="py-12 font-mono text-[#3c1c62] font-bold">Generating Meezan Bank Quick Account Transactions Statement...</div>').show();
    $('#meezan-statement-rendered-content').addClass('hidden');

    $.getJSON('/atm/api/statements/generate', payload, function(res) {
        $('#meezan-output-placeholder').hide();
        if (res.success && res.data && res.data.rendered_html) {
            $('#meezan-statement-rendered-content').html(res.data.rendered_html).removeClass('hidden');
        } else {
            $('#meezan-output-placeholder').html('<div class="text-red-600 font-bold py-12">' + (res.message || 'Error generating statement.') + '</div>').show();
        }
    }).fail(function() {
        $('#meezan-output-placeholder').html('<div class="text-red-600 font-bold py-12">Failed to generate Meezan statement from server.</div>').show();
    });
}

$('#btn-meezan-print').on('click', function() {
    var acc = resolveMeezanAccount();
    var accId = acc ? acc.id : $('#meezan-account-id').val();
    if (!accId) {
        alert('Please select an Account Number first.');
        return;
    }

    var params = new URLSearchParams({
        account_id: accId,
        start_date: $('#meezan-start-date').val(),
        end_date: $('#meezan-end-date').val(),
        format: 'meezan',
        bank_name: 'Meezan Bank Limited',
        account_title: $('#meezan-customer-title').val() || '',
        account_number: $('#meezan-account-number').val() || '',
        address: $('#meezan-customer-address').val() || '',
        branch_name: $('#meezan-branch-name').val() || '',
        branch_address: $('#meezan-branch-address').val() || '',
        old_account_no: $('#meezan-old-account-no').val() || '',
        product: $('#meezan-product').val() || '',
        currency: $('#meezan-currency').val() || 'Pakistan Rupee',
        iban: $('#meezan-iban').val() || '',
        opening_balance: $('#meezan-opening-balance').val() || '',
        generated_by: $('#meezan-generated-by').val() || '',
        print_date: $('#meezan-print-date').val() || ''
    });

    window.open('/atm/statements/print.php?' + params.toString(), '_blank');
});

// Auto-select initial account on page load if provided
$(function() {
    var initId = <?= (int)($selectedAccountId ?: 0) ?>;
    if (initId > 0 && accountsById[initId]) {
        var acc = accountsById[initId];
        $('#meezan-account-code-input').val(acc.account_identifier || acc.id);
        populateMeezanFields(acc);
        executeMeezanGeneration();
    } else if (accountsList.length > 0) {
        // Try finding any account associated with Meezan Bank first
        var meezanAcc = accountsList.find(function(a) {
            return String(a.bank_name).toLowerCase().indexOf('meezan') !== -1;
        });
        if (meezanAcc) {
            $('#meezan-account-code-input').val(meezanAcc.account_identifier || meezanAcc.id);
            populateMeezanFields(meezanAcc);
            executeMeezanGeneration();
        } else {
            // Default to first account
            $('#meezan-account-code-input').val(accountsList[0].account_identifier || accountsList[0].id);
            populateMeezanFields(accountsList[0]);
            executeMeezanGeneration();
        }
    }
});
